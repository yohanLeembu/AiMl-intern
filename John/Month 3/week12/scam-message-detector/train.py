"""
Train the scam message detector.

    python train.py                 # uses data/spam.csv
    python train.py path/to/file    # or point at another copy of the dataset

Steps: load -> clean -> split -> compare models (cross-validation) ->
tune the best model -> evaluate once on the test set -> save the model
and a results table.
"""

import sys
from pathlib import Path

import joblib
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import (accuracy_score, confusion_matrix, f1_score,
                             precision_score, recall_score)
from sklearn.model_selection import (GridSearchCV, StratifiedKFold,
                                     cross_validate, train_test_split)

import spamlib

ROOT = Path(__file__).resolve().parent
DATA_PATH = ROOT / "data" / "spam.csv"
MODEL_PATH = ROOT / "models" / "scam_model.joblib"
RESULTS_PATH = ROOT / "reports" / "results.md"
THRESHOLD = 0.5


def main():
    # Windows consoles can choke on odd characters in messages; never crash on print
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(errors="replace")

    data_path = Path(sys.argv[1]) if len(sys.argv) > 1 else DATA_PATH

    # 1. Load + clean
    df, log = spamlib.clean_data(spamlib.load_data(data_path))
    print("Cleaning log:", log)
    spam_pct = df["label_num"].mean() * 100
    print(f"Final: {len(df)} messages, {spam_pct:.1f}% spam")

    # 2. Split BEFORE fitting anything; stratify keeps the spam share equal in both parts
    X_train, X_test, y_train, y_test = train_test_split(
        df["text"], df["label_num"], test_size=0.2,
        stratify=df["label_num"], random_state=spamlib.RANDOM_STATE)
    print(f"Train: {len(X_train)}  Test: {len(X_test)}")

    # 3. Compare models with 5-fold cross-validation on the training set only
    cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=spamlib.RANDOM_STATE)
    scoring = {"precision": "precision", "recall": "recall", "f1": "f1"}
    cv_rows = []
    for name, clf in spamlib.candidate_models().items():
        scores = cross_validate(spamlib.build_pipeline(clf), X_train, y_train,
                                cv=cv, scoring=scoring)
        row = {"model": name,
               "precision": scores["test_precision"].mean(),
               "recall": scores["test_recall"].mean(),
               "f1": scores["test_f1"].mean()}
        cv_rows.append(row)
        print(f"  {name:20s} precision={row['precision']:.3f} "
              f"recall={row['recall']:.3f} f1={row['f1']:.3f}")

    # 4. Tune the model we ship. Logistic regression is the final choice because its
    #    word weights let the app explain WHY a message was flagged.
    grid = GridSearchCV(
        spamlib.build_pipeline(LogisticRegression(class_weight="balanced", max_iter=1000)),
        param_grid={"clf__C": [0.1, 1, 10, 100]},
        scoring="f1", cv=cv)
    grid.fit(X_train, y_train)
    best_c = grid.best_params_["clf__C"]
    final = grid.best_estimator_            # already refit on the whole training set
    print(f"Best C = {best_c} (cv f1 = {grid.best_score_:.3f})")

    # 5. Final, one-time evaluation on the untouched test set
    proba = final.predict_proba(X_test)[:, 1]
    pred = (proba >= THRESHOLD).astype(int)
    tn, fp, fn, tp = confusion_matrix(y_test, pred).ravel()
    test = {
        "accuracy": accuracy_score(y_test, pred),
        "precision": precision_score(y_test, pred),
        "recall": recall_score(y_test, pred),
        "f1": f1_score(y_test, pred),
    }
    print("Test set:", {k: round(v, 3) for k, v in test.items()},
          f"| TN={tn} FP={fp} FN={fn} TP={tp}")

    # 6. Which words matter most?
    vec = final.named_steps["tfidf"]
    names = vec.get_feature_names_out()
    coef = final.named_steps["clf"].coef_[0]
    order = coef.argsort()
    top_spam = [(spamlib.pretty_term(names[i]), coef[i]) for i in order[::-1][:15]]
    top_ham = [(spamlib.pretty_term(names[i]), coef[i]) for i in order[:15]]
    print("Top spam words:", ", ".join(t for t, _ in top_spam))

    # 7. Save the model + a results table
    MODEL_PATH.parent.mkdir(exist_ok=True)
    RESULTS_PATH.parent.mkdir(exist_ok=True)
    joblib.dump({"pipeline": final, "threshold": THRESHOLD}, MODEL_PATH)
    print("Saved", MODEL_PATH)

    lines = [
        "# Results (generated by train.py)", "",
        f"Messages after cleaning: **{len(df)}** ({spam_pct:.1f}% spam). "
        f"Train: {len(X_train)}, test: {len(X_test)}.", "",
        "## Model comparison (5-fold cross-validation on the training set)", "",
        "| Model | Precision | Recall | F1 |", "|---|---|---|---|",
    ]
    for r in cv_rows:
        lines.append(f"| {r['model']} | {r['precision']:.3f} | {r['recall']:.3f} | {r['f1']:.3f} |")
    lines += [
        "", f"## Final model: Logistic Regression (C = {best_c}), test set", "",
        "| Accuracy | Precision | Recall | F1 |", "|---|---|---|---|",
        f"| {test['accuracy']:.3f} | {test['precision']:.3f} | {test['recall']:.3f} | {test['f1']:.3f} |",
        "", "| | Predicted safe | Predicted scam |", "|---|---|---|",
        f"| **Actually safe** | {tn} | {fp} |",
        f"| **Actually scam** | {fn} | {tp} |",
        "", f"- {fp} real messages wrongly flagged as scam (false positives)",
        f"- {fn} scams that slipped through (false negatives)", "",
        "## Strongest scam words", "", ", ".join(t for t, _ in top_spam), "",
        "## Strongest safe words", "", ", ".join(t for t, _ in top_ham), "",
    ]
    RESULTS_PATH.write_text("\n".join(lines), encoding="utf-8")
    print("Saved", RESULTS_PATH)

    # Quick sanity check on two messages written for this project
    bundle = {"pipeline": final, "threshold": THRESHOLD}
    for msg in ["URGENT! You have won a 1000 prize. Call 09012345678 now to claim!",
                "Are we still meeting at 6 for dinner tonight?"]:
        r = spamlib.predict_message(bundle, msg, names)
        print(f"  score={r['score']:.2f} scam={r['is_scam']} :: {msg[:50]}")


if __name__ == "__main__":
    main()
